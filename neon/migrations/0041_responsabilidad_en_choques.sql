--   2. QA.
--   3. Producción.
--
-- No siembra datos de prueba ni toca filas.
--
-- Vuelta atrás:
--   1. ALTER TABLE public.cases DROP COLUMN IF EXISTS responsabilidad;
--   2. node scripts/migrate.mjs --env <VAR> --forget 0041
-- =============================================================================

